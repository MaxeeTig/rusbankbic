/**
 * Converts Windows-1251 encoded ArrayBuffer to UTF-8 string
 * This is needed because ED807 XML files from CBR are encoded in Windows-1251
 */
export function convertWindows1251ToUTF8(buffer: ArrayBuffer): string {
  const bytes = new Uint8Array(buffer);
  
  // Check the XML declaration to detect encoding
  // Read first 200 bytes to check for encoding declaration
  const firstBytes = bytes.slice(0, Math.min(200, bytes.length));
  let xmlStart = '';
  for (let i = 0; i < firstBytes.length; i++) {
    if (firstBytes[i] < 0x80) {
      xmlStart += String.fromCharCode(firstBytes[i]);
    } else {
      // Found non-ASCII byte, likely Windows-1251
      break;
    }
  }
  
  // If XML declares Windows-1251, use manual conversion
  if (xmlStart.includes('encoding="Windows-1251"') || 
      xmlStart.includes("encoding='Windows-1251'") ||
      xmlStart.includes('encoding="windows-1251"') ||
      xmlStart.includes("encoding='windows-1251'")) {
    console.log('Detected Windows-1251 encoding, using manual conversion');
    return convertWindows1251Manual(bytes);
  }
  
  // Try TextDecoder with windows-1251 (may not be supported)
  try {
    const decoder = new TextDecoder('windows-1251', { fatal: false });
    const decoded = decoder.decode(bytes);
    // Check if decoding produced valid Cyrillic characters
    // If we see replacement characters or no Cyrillic, use manual conversion
    if (!decoded.includes('�') && decoded.match(/[А-Яа-яЁё]/)) {
      console.log('TextDecoder windows-1251 worked');
      return decoded;
    }
  } catch (e) {
    // TextDecoder doesn't support windows-1251
  }
  
  // Default to manual conversion for ED807 files (they're always Windows-1251)
  console.log('Using manual Windows-1251 conversion');
  return convertWindows1251Manual(bytes);
}

/**
 * Manual conversion for Windows-1251 to UTF-8
 * Covers the Cyrillic range (0x80-0xFF)
 */
function convertWindows1251Manual(bytes: Uint8Array): string {
  const result: string[] = [];
  
  for (let i = 0; i < bytes.length; i++) {
    const byte = bytes[i];
    
    if (byte < 0x80) {
      // ASCII range - no conversion needed
      result.push(String.fromCharCode(byte));
    } else {
      // Windows-1251 Cyrillic range
      // Map Windows-1251 to Unicode
      const unicode = windows1251ToUnicode[byte];
      if (unicode !== undefined) {
        // All Cyrillic characters are in BMP (Basic Multilingual Plane), so fromCharCode works
        result.push(String.fromCharCode(unicode));
      } else {
        // Unknown character - keep as-is (shouldn't happen with complete mapping)
        // This might be a control character or special symbol
        result.push(String.fromCharCode(byte));
      }
    }
  }
  
  return result.join('');
}

